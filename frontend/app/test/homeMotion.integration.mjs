import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { execFileSync } from 'node:child_process'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const output = resolve(process.env.VISUAL_OUTPUT || '../docs/testing/screenshots/site-visual-stabilization-20261011')
await mkdir(output, { recursive: true })
const server = await chromium.launchServer({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) })
const watchdog = setTimeout(() => { execFileSync('taskkill', ['/PID', String(server.process().pid), '/T', '/F'], { windowsHide: true, stdio: 'ignore' }); process.exit(124) }, 60000)
const browser = await chromium.connect(server.wsEndpoint())
const evidence = []
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: 'no-preference' })
  const page = await context.newPage()
  await page.goto('http://127.0.0.1:3000/'); await page.locator('[data-account-entry]:not([disabled])').waitFor()
  const stack = page.locator('#stack'), track = page.locator('#stack .moving').first()
  await stack.scrollIntoViewIfNeeded(); await page.mouse.move(0, 0)
  await page.waitForFunction(() => document.querySelector('#stack')?.dataset.paused === 'false')
  const animationTime = () => track.evaluate(el => el.getAnimations()[0].currentTime)
  const first = await animationTime(); await page.waitForTimeout(350); assert.ok(await animationTime() > first)
  const seam = await track.evaluate(el => ({ width: el.getBoundingClientRect().width, rows: [...el.children].map(row => row.getBoundingClientRect().width) }))
  assert.ok(Math.abs(seam.width - seam.rows[0] * 2) < .5 && Math.abs(seam.rows[0] - seam.rows[1]) < .5, '无缝重复周期宽度一致')
  assert.equal(await track.locator('ul[aria-hidden="true"]').count(), 1)
  for (let frame = 0; frame < 3; frame++) {
    await stack.screenshot({ path: resolve(output, `home-stack-frame-${frame}.png`) })
    evidence.push({ frame, time: await animationTime() }); await page.waitForTimeout(350)
  }
  const stackCard = await page.locator('#stack .tech-card').first().boundingBox()
  await page.mouse.move(stackCard.x + 30, stackCard.y + 30)
  const pausedAt = await animationTime(); await page.waitForTimeout(200)
  assert.ok(Math.abs(await animationTime() - pausedAt) < 25, '鼠标悬停暂停')
  await page.mouse.move(0, 0)
  await page.getByRole('button', { name: '暂停技术栈滚动' }).click()
  const manualTime = await animationTime(); await page.waitForTimeout(200); assert.ok(Math.abs(await animationTime() - manualTime) < 25)
  await page.getByRole('button', { name: '继续技术栈滚动' }).click()
  const themeTime = await animationTime()
  await page.locator('.theme-toggle').click(); assert.ok(await animationTime() >= themeTime, '切换主题不重置动画')
  const card = page.locator('.focus-card').first()
  await card.scrollIntoViewIfNeeded(); await page.mouse.move(0, 0)
  const neighbor = page.locator('.focus-card').nth(1), before = await neighbor.boundingBox()
  await card.hover(); await page.waitForTimeout(260)
  assert.notEqual(await card.evaluate(el => getComputedStyle(el).transform), 'none')
  assert.deepEqual(await neighbor.boundingBox(), before, '移动不改变周围布局')
  await page.screenshot({ path: resolve(output, 'home-card-hover.png') })
  await page.evaluate(() => { Object.defineProperty(document, 'visibilityState', { value: 'hidden', configurable: true }); document.dispatchEvent(new Event('visibilitychange')) })
  assert.equal(await stack.getAttribute('data-paused'), 'true')
  await page.evaluate(() => { delete document.visibilityState; document.dispatchEvent(new Event('visibilitychange')) })
  await stack.scrollIntoViewIfNeeded(); await page.mouse.move(0, 0)
  await page.evaluate(() => { window.__motionTasks = []; new PerformanceObserver(e => window.__motionTasks.push(...e.getEntries().map(t => t.duration))).observe({ type: 'longtask' }) })
  const cdp = await context.newCDPSession(page); await cdp.send('Performance.enable')
  const metrics = async () => Object.fromEntries((await cdp.send('Performance.getMetrics')).metrics.map(x => [x.name, x.value]))
  const start = await metrics(); await page.waitForTimeout(1600); const end = await metrics()
  const tasks = await page.evaluate(() => window.__motionTasks)
  assert.ok((end.TaskDuration - start.TaskDuration) * 1000 < 250, '动画期间主线程负载受控')
  assert.ok(Math.max(0, ...tasks) < 150)
  evidence.push({ animationTaskMs: Math.round((end.TaskDuration - start.TaskDuration) * 1000), longTasks: tasks })
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
  await page.waitForFunction(() => document.querySelector('#stack')?.dataset.paused === 'true')
  await context.close()
  const reduced = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, reducedMotion: 'reduce' })
  const mobile = await reduced.newPage(); await mobile.goto('http://127.0.0.1:3000/')
  await mobile.locator('[data-account-entry]:not([disabled])').waitFor()
  assert.equal(await mobile.locator('#stack .moving').first().evaluate(el => getComputedStyle(el).animationName), 'none')
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await mobile.locator('#stack').screenshot({ path: resolve(output, 'home-stack-mobile-reduced.png') })
  await reduced.close()
  console.log(JSON.stringify({ result: 'passed', frames: evidence }))
} finally { clearTimeout(watchdog); await browser.close(); await server.close() }
await writeFile(resolve(output, 'home-motion.json'), JSON.stringify(evidence, null, 2))
