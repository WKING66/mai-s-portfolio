-- 将历史快照模型纠正为正式正文/工作草稿；来源数据必须先有外部可恢复备份。
-- 新关系由业务事务、修订检查和资源锁负责，不创建物理外键。
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM document d LEFT JOIN document_version v ON v.id = d.current_version_id
        WHERE d.current_version_id IS NOT NULL AND (v.id IS NULL OR v.document_id <> d.id)
    ) OR EXISTS (
        SELECT 1 FROM blog_post b LEFT JOIN document_version v ON v.id = b.published_version_id
        WHERE b.published_version_id IS NOT NULL AND (v.id IS NULL OR v.document_id <> b.document_id)
    ) THEN
        RAISE EXCEPTION 'Document pointer ownership is inconsistent; migration stopped';
    END IF;
    IF EXISTS (SELECT 1 FROM blog_post WHERE status = 1 AND published_version_id IS NULL) THEN
        RAISE EXCEPTION 'Published blog has no formal content; migration stopped';
    END IF;
END $$;

CREATE TABLE document_content (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL,
    stage VARCHAR(16) NOT NULL CHECK (stage IN ('DRAFT', 'PUBLISHED')),
    title VARCHAR(200),
    summary TEXT,
    content TEXT NOT NULL,
    reading_time_minutes SMALLINT NOT NULL,
    updated_by BIGINT NOT NULL,
    created_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_document_content_stage UNIQUE (document_id, stage)
);

INSERT INTO document_content
    (id, document_id, stage, title, summary, content, reading_time_minutes, updated_by, created_at, updated_at)
SELECT v.id, v.document_id, 'PUBLISHED', v.title, v.summary, v.markdown_content,
       v.reading_time_minutes, v.created_by, v.created_at, v.created_at
FROM blog_post b JOIN document_version v ON v.id = b.published_version_id;

INSERT INTO document_content
    (id, document_id, stage, title, summary, content, reading_time_minutes, updated_by, created_at, updated_at)
SELECT v.id, v.document_id, 'DRAFT', v.title, v.summary, v.markdown_content,
       v.reading_time_minutes, v.created_by, v.created_at, v.created_at
FROM document d JOIN document_version v ON v.id = d.current_version_id
LEFT JOIN blog_post b ON b.document_id = d.id
WHERE b.published_version_id IS DISTINCT FROM d.current_version_id;

CREATE TABLE document_resource (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_id BIGINT NOT NULL,
    asset_id BIGINT,
    resource_key VARCHAR(36) NOT NULL,
    resource_type SMALLINT NOT NULL,
    source_kind SMALLINT NOT NULL,
    original_uri VARCHAR(2048),
    status SMALLINT NOT NULL,
    error_message VARCHAR(512),
    sort_order INTEGER NOT NULL,
    CONSTRAINT uk_document_resource_key UNIQUE (content_id, resource_key)
);
CREATE INDEX idx_document_resource_asset ON document_resource (asset_id, content_id);
CREATE INDEX idx_document_resource_order ON document_resource (content_id, sort_order, id);
INSERT INTO document_resource
    (id, content_id, asset_id, resource_key, resource_type, source_kind, original_uri, status, error_message, sort_order)
SELECT r.id, r.document_version_id, r.media_id, r.resource_key, r.resource_type,
       r.source_kind, r.source_reference, r.status, r.error_message, r.sort_order
FROM document_version_asset r JOIN document_content c ON c.id = r.document_version_id;

CREATE TABLE document_content_tag (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    slug VARCHAR(120) NOT NULL,
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('TOPIC', 'TECH')),
    CONSTRAINT uk_document_content_tag UNIQUE (content_id, tag_id)
);
CREATE INDEX idx_document_content_tag_reverse ON document_content_tag (tag_id, content_id);
INSERT INTO document_content_tag (id, content_id, tag_id, name, slug, kind)
SELECT r.id, r.document_version_id, r.tag_id, r.tag_name_snapshot, r.tag_slug_snapshot,
       CASE t.kind WHEN 0 THEN 'TOPIC' ELSE 'TECH' END
FROM document_version_tag r
JOIN document_content c ON c.id = r.document_version_id JOIN tag t ON t.id = r.tag_id;

-- 保持旧 ID 高水位，避免重新使用已删除历史快照的身份。
SELECT setval(pg_get_serial_sequence('document_content', 'id'),
    GREATEST(COALESCE(MAX(id), 1), 1), COUNT(*) > 0) FROM document_version;
SELECT setval(pg_get_serial_sequence('document_resource', 'id'),
    GREATEST(COALESCE(MAX(id), 1), 1), COUNT(*) > 0) FROM document_version_asset;
SELECT setval(pg_get_serial_sequence('document_content_tag', 'id'),
    GREATEST(COALESCE(MAX(id), 1), 1), COUNT(*) > 0) FROM document_version_tag;

