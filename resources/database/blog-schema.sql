    logo_key VARCHAR(160),
    is_featured SMALLINT NOT NULL,
    sort_order INTEGER NOT NULL,
    CONSTRAINT uk_tag_kind_name UNIQUE (kind, normalized_name)
);
CREATE UNIQUE INDEX uk_tag_slug_ci ON tag (LOWER(slug));
CREATE INDEX idx_tag_display ON tag (kind, group_code, is_featured, sort_order);
COMMENT ON TABLE tag IS '文章主题及技术栈等全局标签';
COMMENT ON COLUMN tag.id IS '全局标签自增主键；项目或文档版本通过此 ID 关联';
COMMENT ON COLUMN tag.kind IS '标签类别数值码：0=文章主题，1=技术能力';
COMMENT ON COLUMN tag.name IS '当前全局展示名称；已发布文档使用版本内名称快照';
COMMENT ON COLUMN tag.normalized_name IS '服务端规范化后的名称，用于同类标签去重';
COMMENT ON COLUMN tag.slug IS '标签稳定公开标识；被公开版本引用后不得改写';
COMMENT ON COLUMN tag.group_code IS '技术标签分组数值码：0=语言，1=框架，2=工具，3=基础设施，4=数据技术；主题标签为空';
COMMENT ON COLUMN tag.logo_key IS '技术 Logo 的受控静态资源键；不是任意网络地址';
COMMENT ON COLUMN tag.is_featured IS '是否在首页重点展示：0=否，1=是';
COMMENT ON COLUMN tag.sort_order IS '同组标签展示顺序；数值越小越靠前';

-- 当前核心：文档身份、最新保存版本指针及乐观锁
CREATE TABLE document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    origin_type SMALLINT NOT NULL,
    current_version_id BIGINT,
    lock_version BIGINT NOT NULL,
    created_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_document_owner FOREIGN KEY (owner_id)
        REFERENCES user_account (id) ON DELETE RESTRICT
);
COMMENT ON TABLE document IS '统一文档身份；当前版本可能仍是未发布草稿';
COMMENT ON COLUMN document.id IS '统一文档自增主键；同一文档可产生多个不可变版本';
COMMENT ON COLUMN document.owner_id IS '文档所有者 user_account.id；首版仅站长可编辑';
COMMENT ON COLUMN document.origin_type IS '创建来源数值码：0=站内创建，1=导入；不决定正文模型';
COMMENT ON COLUMN document.current_version_id IS '最新已保存版本；不可据此判断访客可见性';
COMMENT ON COLUMN document.lock_version IS '文档写入乐观锁计数；与内容版本号不同';
COMMENT ON COLUMN document.created_at IS '文档身份创建时间；应用写入 UTC，精度毫秒';
COMMENT ON COLUMN document.updated_at IS '文档最新保存时间；不等于公开重新发布时间';

-- 当前核心：不可变正文版本
CREATE TABLE document_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL,
    version_number BIGINT NOT NULL,
    title VARCHAR(200),
    summary TEXT,
    markdown_content TEXT NOT NULL,
    reading_time_minutes SMALLINT NOT NULL,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_document_version_number UNIQUE (document_id, version_number),
    CONSTRAINT fk_document_version_document FOREIGN KEY (document_id)
        REFERENCES document (id) ON DELETE RESTRICT,
    CONSTRAINT fk_document_version_author FOREIGN KEY (created_by)
        REFERENCES user_account (id) ON DELETE RESTRICT
);
CREATE INDEX idx_document_version_recent ON document_version (document_id, created_at DESC, id DESC);
-- 文档与版本互相引用：两表创建完成后，补上最新版本指针外键。
ALTER TABLE document ADD CONSTRAINT fk_document_current_version
    FOREIGN KEY (current_version_id) REFERENCES document_version (id) ON DELETE RESTRICT;
COMMENT ON TABLE document_version IS '不可变文档快照：Markdown、标题、摘要和派生阅读时长';
COMMENT ON COLUMN document_version.id IS '不可变内容版本自增主键；供博客发布指针和后续索引引用';
COMMENT ON COLUMN document_version.document_id IS '所属 document.id；一个文档对应多个版本';
COMMENT ON COLUMN document_version.version_number IS '同一文档内单调增加的内容版本号';
COMMENT ON COLUMN document_version.title IS '此版本的标题快照；草稿可为空，发布前必填';
COMMENT ON COLUMN document_version.summary IS '此版本的摘要快照；草稿可为空，发布前必填';
COMMENT ON COLUMN document_version.markdown_content IS '此版本唯一可编辑正文真源；图片和附件使用 asset:// 内部引用';
COMMENT ON COLUMN document_version.reading_time_minutes IS '从本版本正文计算；草稿保存不改变已发布版本的阅读时长';
COMMENT ON COLUMN document_version.created_by IS '创建该版本的 user_account.id';
COMMENT ON COLUMN document_version.created_at IS '此版本创建时间；写入后不得修改';

-- 当前核心：每个版本的资源引用与处理状态
CREATE TABLE document_version_asset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_version_id BIGINT NOT NULL,
    media_id BIGINT,
    role SMALLINT NOT NULL,
    alt_text VARCHAR(500),
    source_reference VARCHAR(2048),
    sort_order INTEGER NOT NULL,
    resource_key VARCHAR(36) NOT NULL,
    resource_type SMALLINT NOT NULL DEFAULT 0,
    source_kind SMALLINT NOT NULL DEFAULT 1,
    status SMALLINT NOT NULL DEFAULT 0,
    error_message VARCHAR(512),
    CONSTRAINT fk_document_asset_version FOREIGN KEY (document_version_id)
        REFERENCES document_version (id) ON DELETE RESTRICT,
    CONSTRAINT fk_document_asset_media FOREIGN KEY (media_id)
        REFERENCES media_asset (id) ON DELETE RESTRICT,
    CONSTRAINT uq_document_resource_key UNIQUE (document_version_id, resource_key)
);
CREATE INDEX idx_document_asset_order ON document_version_asset (document_version_id, sort_order, id);
CREATE INDEX idx_document_asset_media ON document_version_asset (media_id, document_version_id);
COMMENT ON TABLE document_version_asset IS '文档版本资源引用；未就绪资源保留来源并允许文件关联为空';
COMMENT ON COLUMN document_version_asset.id IS '版本资源关系自增主键';
