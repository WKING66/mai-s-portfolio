BEGIN;

-- 共享依赖：账号身份、文档所有者、版本创建者、资源上传者
CREATE TABLE user_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL,
    type SMALLINT NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    status SMALLINT NOT NULL,
    created_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL,
    credential_version BIGINT NOT NULL DEFAULT 0 CHECK (credential_version >= 0)
);
CREATE UNIQUE INDEX uk_user_account_username_ci ON user_account (LOWER(username));
COMMENT ON TABLE user_account IS '站长与普通访客账号；普通账号不得获取管理权限';
COMMENT ON COLUMN user_account.id IS '账号自增主键；仅用于站内关联';
COMMENT ON COLUMN user_account.username IS '登录用户名；按小写唯一索引避免大小写重复';
COMMENT ON COLUMN user_account.type IS '账号类型数值码：0=站长，1=普通访客；由服务端枚举校验';
COMMENT ON COLUMN user_account.password_hash IS '服务端持久化的密码摘要；不得返回接口或写入日志';
COMMENT ON COLUMN user_account.status IS '账号状态数值码：0=禁用，1=启用';
COMMENT ON COLUMN user_account.created_at IS '账号创建时间；应用写入 UTC，精度毫秒';
COMMENT ON COLUMN user_account.updated_at IS '账号资料或状态最后更新时间；应用写入 UTC，精度毫秒';
COMMENT ON COLUMN user_account.credential_version IS '账号凭据版本；修改密码时递增，会话保存登录时版本并在请求时校验';

-- 共享依赖：文件元数据；不保存 OSS 文件字节
CREATE TABLE media_asset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_type SMALLINT NOT NULL,
    storage_key VARCHAR(512),
    source_type SMALLINT NOT NULL,
    source_host VARCHAR(255),
    original_filename VARCHAR(255),
    mime_type VARCHAR(100),
    byte_size BIGINT,
    sha256 BYTEA,
    width INTEGER,
    height INTEGER,
    status SMALLINT NOT NULL,
    created_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL,
    usage VARCHAR(32) NOT NULL,
    uploader_account_id BIGINT,
    CONSTRAINT uk_media_asset_storage_key UNIQUE (storage_key),
    CONSTRAINT fk_asset_uploader FOREIGN KEY (uploader_account_id)
        REFERENCES user_account (id) ON DELETE RESTRICT
);
CREATE INDEX idx_media_asset_status_created ON media_asset (status, created_at);
COMMENT ON TABLE media_asset IS '受控二进制资源元数据；实际字节由对象存储管理';
COMMENT ON COLUMN media_asset.id IS '资源自增主键；asset:// 引用中的内部资源 ID，不代表公开授权';
COMMENT ON COLUMN media_asset.asset_type IS '资源类型：0=图片、1=文档、2=普通附件';
COMMENT ON COLUMN media_asset.storage_key IS '对象存储键；资源 READY 后不得原地覆盖';
COMMENT ON COLUMN media_asset.source_type IS '资源来源数值码：0=本地笔记，1=网络地址，2=编辑器上传';
COMMENT ON COLUMN media_asset.source_host IS '网络来源的主机名；不保存查询参数、令牌或完整 URL';
COMMENT ON COLUMN media_asset.original_filename IS '上传或导入时的原始文件名；仅用于展示与审计';
COMMENT ON COLUMN media_asset.mime_type IS '经服务端内容校验后的媒体 MIME 类型';
COMMENT ON COLUMN media_asset.byte_size IS '二进制对象大小，单位字节';
COMMENT ON COLUMN media_asset.sha256 IS '二进制对象的 SHA-256 摘要，原始 32 字节';
COMMENT ON COLUMN media_asset.width IS '图片像素宽度；非图片可为空';
COMMENT ON COLUMN media_asset.height IS '图片像素高度；非图片可为空';
COMMENT ON COLUMN media_asset.status IS '资源状态数值码：0=待处理，1=可用，2=失败；只有可用资源可进入公开版本';
COMMENT ON COLUMN media_asset.created_at IS '资源记录创建时间；应用写入 UTC，精度毫秒';
COMMENT ON COLUMN media_asset.updated_at IS '资源状态或元数据最后更新时间；应用写入 UTC，精度毫秒';
COMMENT ON COLUMN media_asset.usage IS '上传用途：AVATAR、IMAGE、ATTACHMENT；封面、截图和博客插图共用 IMAGE';
COMMENT ON COLUMN media_asset.uploader_account_id IS '上传时的有效账号；历史无法确定归属的资产保留 NULL，不允许通过新接口绑定为本人头像';

-- 共享标签目录：已有表，但当前博客未接入标签保存
CREATE TABLE tag (
